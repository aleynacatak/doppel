// AppleScript ↔ ExtendScript bridge shared by the Adobe adapters (InDesign, Photoshop). Each call writes the
// assembled script to a temp .jsx file and asks the app (by bundle id, so the version folder name doesn't
// matter) to run it with one JSON argument. Arguments go to osascript with execFile, never through a shell string.

export interface AdobeAppSpec {
  appId: AppId;
  /** e.g. "com.adobe.InDesign" */
  bundleId: string;
  /** Short name for messages, e.g. "InDesign". */
  shortName: string;
  /** Folder name prefix in /Applications, e.g. "Adobe InDesign" (fallback install check). */
  folderPrefix: string;
  /** The app's AppleScript command for running JavaScript with arguments. */
  runCommand: "do script" | "do javascript";
  /**
   * How the script reaches the app: "file" passes the .jsx file (InDesign); "text" reads the file in osascript
   * and passes its text (Photoshop 2026 answers "Can't get file" (-1728) for script files in the temp folder).
   */
  delivery: "file" | "text";
  /** ExtendScript run before the routine (inside the try) and in its finally block. */
  prologue: string[];
  epilogue: string[];
  /** Helper library prepended to every script (after the JSON polyfill). */
  library: string;
}

export type BridgeErrorKind = "permission-denied" | "not-running" | "timeout" | "script" | "bridge";

export class BridgeError extends Error {
  constructor(
    readonly kind: BridgeErrorKind,
    message: string,
    readonly detail?: string,
    readonly line?: number,
  ) {
    super(message);
    this.name = "BridgeError";
  }
}

const ROUTINE_START = "/*__DOPPL_ROUTINE_START__*/";

export interface AssembledScript {
  source: string;
  /** Line in `source` where the routine body starts (1-based), for mapping error lines. */
  routineStartLine?: number;
}

/** Marks where a routine body starts inside `main`, so script errors can point at the routine's own lines. */
export const routineStartMarker = ROUTINE_START;

/**
 * Every script is `function (input) { ... return data; }`. The app receives one JSON string argument and
 * returns one JSON string: { ok: true, data } or { ok: false, error, line }.
 */
export function assembleScript(spec: Pick<AdobeAppSpec, "library" | "prologue" | "epilogue">, main: string): AssembledScript {
  const source = [
    "// Generated by Doppl. Safe to delete.",
    JSON2,
    spec.library,
    'var __dopplArgs = (typeof arguments !== "undefined" && arguments.length > 0) ? arguments[0] : "{}";',
    "var __dopplResult = (function (argsJson) {",
    "  var input;",
    "  try { input = JSON.parse(argsJson); } catch (e) {",
    '    return JSON.stringify({ ok: false, error: "Doppl couldn\'t read the script parameters." });',
    "  }",
    ...spec.prologue.map((l) => `  ${l}`),
    "  try {",
    `    var data = (${main})(input);`,
    "    return JSON.stringify({ ok: true, data: data === undefined ? null : data });",
    "  } catch (e) {",
    "    return JSON.stringify({ ok: false, error: String(e && e.message ? e.message : e), line: e && e.line ? e.line : null });",
    "  } finally {",
    ...spec.epilogue.map((l) => `    ${l}`),
    "  }",
    "})(__dopplArgs);",
    "__dopplResult;",
  ].join("\n");
  const lines = source.split("\n");
  const marker = lines.findIndex((l) => l.includes(ROUTINE_START));
  return { source, routineStartLine: marker >= 0 ? marker + 2 : undefined };
}

/** The AppleScript that runs a .jsx file in the app with one JSON argument and a timeout. */
export function runnerScript(spec: Pick<AdobeAppSpec, "bundleId" | "runCommand" | "delivery">): string {
  const script = spec.delivery === "text" ? "jsxSource" : "jsxFile";
  const call =
    spec.runCommand === "do script"
      ? `do script ${script} language javascript with arguments {jsonArgs}`
      : `do javascript ${script} with arguments {jsonArgs} show debugger never`;
  const load = spec.delivery === "text" ? "set jsxSource to read (POSIX file jsxPath) as «class utf8»" : "set jsxFile to POSIX file jsxPath";
  return `
on run argv
	set jsxPath to item 1 of argv
	set jsonArgs to item 2 of argv
	set timeoutSecs to (item 3 of argv) as integer
	${load}
	with timeout of timeoutSecs seconds
		tell application id "${spec.bundleId}"
			set scriptResult to ${call}
		end tell
	end timeout
	return scriptResult
end run
`;
}

/** Turns osascript's stderr into a plain-language error. */
export function mapAppleScriptError(stderr: string, shortName: string): BridgeError {
  const code = Number(stderr.match(/\((-?\d+)\)\s*$/m)?.[1]);
  const detail = stderr.trim();
  if (code === -1743) {
    return new BridgeError(
      "permission-denied",
      `Doppl isn't allowed to control ${shortName}. Turn it on in System Settings → Privacy & Security → Automation.`,
      detail,
    );
  }
  if (code === -600 || code === -609) return new BridgeError("not-running", `${shortName} isn't running.`, detail);
  if (code === -1712) return new BridgeError("timeout", `${shortName} didn't answer in time.`, detail);
  // Positive codes come from the app itself, e.g. "got an error: Illegal use of reserved word 'long' (9)".
  const fromApp = detail.match(/got an error: ([\s\S]*?) \((\d+)\)$/);
  if (fromApp) return new BridgeError("script", fromApp[1].trim(), detail);
  return new BridgeError("bridge", `${shortName} couldn't run the script.`, detail);
}

/** Reads the app's JSON answer ({ ok, data } or { ok: false, error, line }). */
export function parseScriptResult<T>(raw: string, shortName: string, routineStartLine?: number): T {
  let parsed: { ok: boolean; data?: T; error?: string; line?: number | null };
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new BridgeError("bridge", `${shortName} returned something Doppl couldn't read.`, raw.slice(0, 500));
  }
  if (!parsed || typeof parsed !== "object") throw new BridgeError("bridge", `${shortName} returned something Doppl couldn't read.`, raw.slice(0, 500));
  if (!parsed.ok) {
    const line = parsed.line && routineStartLine ? parsed.line - routineStartLine + 1 : undefined;
    throw new BridgeError("script", parsed.error || "The script failed.", parsed.error, line && line > 0 ? line : undefined);
  }
  return parsed.data as T;
}

type ExecFile = typeof execFile;

/** One Adobe app's bridge: status checks and a queue of scripts (the app runs one at a time). */
export class AdobeBridge {
  private queue: Promise<unknown> = Promise.resolve();
  private busy = false;

  constructor(
    readonly spec: AdobeAppSpec,
    /** Injectable for tests. */
    private readonly exec: ExecFile = execFile,
  ) {}

  private osascript(args: string[], timeoutMs: number): Promise<string> {
    return new Promise((resolve, reject) => {
      this.exec(
        "/usr/bin/osascript",
        args,
        { timeout: timeoutMs, maxBuffer: 256 * 1024 * 1024, encoding: "utf8" },
        (error, stdout, stderr) => {
          if (error) {
            const err = error as NodeJS.ErrnoException & { killed?: boolean; signal?: string };
            if (err.killed || err.signal === "SIGTERM") {
              return reject(new BridgeError("timeout", `${this.spec.shortName} didn't answer in time.`));
            }
            return reject(mapAppleScriptError(String(stderr || err.message), this.spec.shortName));
          }
          resolve(String(stdout).replace(/\n$/, ""));
        },
      );
    });
  }

  isBusy() {
    return this.busy;
  }

  /** True if the app is running. Never launches it. */
  async isRunning(): Promise<boolean> {
    try {
      const out = await this.osascript(["-e", `application id "${this.spec.bundleId}" is running`], 5000);
      return out.trim() === "true";
    } catch {
      return false;
    }
  }

  async activate(): Promise<void> {
    await this.osascript(["-e", `tell application id "${this.spec.bundleId}" to activate`], 10000);
  }

  /** True if the app is installed (Spotlight first, then the Applications folder). */
  async isInstalled(): Promise<boolean> {
    const viaSpotlight = await new Promise<boolean>((resolve) => {
      this.exec("/usr/bin/mdfind", [`kMDItemCFBundleIdentifier == '${this.spec.bundleId}'`], { timeout: 5000 }, (err, stdout) => {
        resolve(!err && String(stdout).trim().length > 0);
      });
    });
    if (viaSpotlight) return true;
    try {
      const entries = await fs.readdir("/Applications");
      return entries.some((e) => e.startsWith(this.spec.folderPrefix));
    } catch {
      return false;
    }
  }

  /**
   * Runs `main` (an ExtendScript `function (input) {…}`) in the app and returns its data.
   * Throws BridgeError with a plain-language message on failure. `label` names the call in the connection log.
   */
  runJsx<T>(main: string, input: unknown, timeoutSec: number, label = "script"): Promise<T> {
    const job = this.queue.then(() => this.execute<T>(main, input, timeoutSec, label));
    this.queue = job.catch(() => undefined);
    return job;
  }

  private async execute<T>(main: string, input: unknown, timeoutSec: number, label: string): Promise<T> {
    this.busy = true;
    const started = Date.now();
    const { source, routineStartLine } = assembleScript(this.spec, main);
    const dir = path.join(os.tmpdir(), "doppl-jsx");
    await fs.mkdir(dir, { recursive: true });
    const file = path.join(dir, `${newId()}.jsx`);
    const args = JSON.stringify(input ?? {});
    // A file the app reads itself gets a UTF-8 BOM so ExtendScript reads non-ASCII text correctly. Text that
    // osascript reads and passes on is decoded there, and a BOM would end up in the script.
    await fs.writeFile(file, this.spec.delivery === "file" ? `﻿${source}` : source, "utf8");
    let ok = false;
    let bytesIn = 0;
    try {
      const raw = await this.osascript(["-e", runnerScript(this.spec), file, args, String(timeoutSec)], (timeoutSec + 5) * 1000);
      bytesIn = raw.length;
      const data = parseScriptResult<T>(raw, this.spec.shortName, routineStartLine);
      ok = true;
      return data;
    } catch (err) {
      if (err instanceof BridgeError && err.kind === "timeout") {
        throw new BridgeError(
          "timeout",
          `${this.spec.shortName} didn't finish within ${timeoutSec} seconds. You can raise the limit in Settings.`,
        );
      }
      throw err;
    } finally {
      this.busy = false;
      connectionLog.add({
        channel: "applescript",
        app: this.spec.appId,
        direction: "out",
        kind: label,
        bytes: args.length + bytesIn,
        ms: Date.now() - started,
        ok,
      });
      fs.rm(file, { force: true }).catch(() => undefined);
    }
  }
}
